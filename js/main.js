const $ = s => document.querySelector(s);
const parse = v => typeof v === "number" ? { l: "", p: v } : { l: v.split("=")[0], p: +v.split("=")[1] };

function priceText(vs) {
  const o = vs.map(parse);
  if (o.length === 1) {
    return o[0].l ? `${o[0].p} сом <small class="text-secondary">(${o[0].l})</small>` : `${o[0].p} сом`;
  }
  return o.map(x => `${x.l}: ${x.p} сом`).join(" · ");
}

